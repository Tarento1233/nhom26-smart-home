"""Browser checks against the isolated Node-RED instance used by the E2E test."""
from playwright.sync_api import sync_playwright, expect


def verify_dashboard(url, state, wait_for, control, data_dir, check, device_connection, environment_delivery, login_credentials):
    control('clock', 'day')
    control('mode', 'AUTO')
    with sync_playwright() as playwright:
        browser = playwright.chromium.launch(channel='chrome', headless=True)
        page = browser.new_page(viewport={'width': 1280, 'height': 1100}, locale='vi-VN')
        errors = []
        page.on('pageerror', lambda error: errors.append(str(error)))
        page.goto(url + '/dashboard/room', wait_until='networkidle')
        if page.url.endswith('/login'):
            page.screenshot(path=str(data_dir / 'login-test-desktop.png'),full_page=True)
            page.get_by_label('Tên đăng nhập',exact=True).fill(login_credentials['username'])
            page.get_by_label('Mật khẩu',exact=True).fill(login_credentials['password'])
            page.get_by_role('button',name='Vào căn phòng',exact=True).click()
            page.wait_for_url('**/dashboard/room')
        page.get_by_role('heading', name='Đèn sáng. Phòng mát. Thật dễ.').wait_for()
        page.get_by_text('Phòng đã kết nối', exact=True).wait_for()
        assert page.locator('.iot-demo').get_attribute('open') is None
        assert page.locator('.iot-history-group').first.is_hidden()
        check('First view explains the purpose and keeps technical settings collapsed')
        page.locator('.iot-demo summary').click()
        page.get_by_role('button',name='Xem lịch sử',exact=True).click()
        expect(page.locator('.iot-history-table tbody tr').first).to_be_visible()
        page.get_by_label('Loại hoạt động',exact=True).select_option('sensor:temp_humid')
        page.get_by_role('button',name='Xem lịch sử',exact=True).click()
        expect(page.locator('.iot-history-table tbody tr').first).to_contain_text('Nhiệt độ / độ ẩm')
        page.screenshot(path=str(data_dir/'database-history-desktop.png'),full_page=True)
        page.locator('.iot-demo summary').click()
        check('Dashboard queries and filters real SQLite history')
        light = page.locator('.iot-device').first
        light.get_by_role('button', name='Tắt đèn phòng', exact=True).click()
        wait_for(lambda s: s['mode'] == 'MANUAL' and s['light'] == 'OFF', 'browser light OFF and MQTT acknowledgement')
        light.get_by_role('button', name='Bật đèn phòng', exact=True).click()
        wait_for(lambda s: s['light'] == 'ON', 'browser light ON and MQTT acknowledgement')
        check('Dashboard buttons send MQTT commands and display ESP32 acknowledgements')

        modes = page.locator('.iot-mode-row')
        thermostat = page.locator('.iot-thermostat')
        expect(thermostat.get_by_label('Nhiệt độ máy lạnh đã đặt', exact=True)).to_have_text('25°C')
        thermostat.get_by_role('button', name='Giảm nhiệt độ máy lạnh', exact=True).click()
        wait_for(lambda s: s['mode']=='MANUAL' and s['acTarget']==24, 'manual temperature step down')
        modes.get_by_role('button', name='Tự động', exact=False).click()
        wait_for(lambda s: s['mode']=='AUTO' and s['acTarget']==25, 'auto profile remains 25')
        thermostat.get_by_role('button', name='Tăng nhiệt độ máy lạnh', exact=True).click()
        wait_for(lambda s: s['mode']=='AUTO' and s['acTarget']==26, 'auto temperature step up keeps mode')
        modes.get_by_role('button', name='Tự điều khiển', exact=False).click()
        wait_for(lambda s: s['mode']=='MANUAL' and s['acTarget']==24, 'manual profile remembered')
        control('manualTemperature',16)
        expect(thermostat.get_by_role('button', name='Giảm nhiệt độ máy lạnh', exact=True)).to_be_disabled()
        control('manualTemperature',31)
        expect(thermostat.get_by_role('button', name='Tăng nhiệt độ máy lạnh', exact=True)).to_be_disabled()
        control('manualTemperature',25)
        control('autoTemperature',25)
        check('Temperature buttons remember each mode and stop at 16C and 31C')
        modes.get_by_role('button', name='Giờ ngủ', exact=False).click()
        wait_for(lambda s: s['mode'] == 'SLEEP' and s['light'] == 'ON', 'browser SLEEP button')
        expect(modes.locator('button.selected strong')).to_have_text('Giờ ngủ')
        modes.get_by_role('button', name='Tự động', exact=False).click()
        wait_for(lambda s: s['mode'] == 'AUTO' and s['light'] == 'ON', 'browser AUTO button')
        if not page.get_by_role('button', name='Bật demo nhanh', exact=True).is_visible():
            page.locator('.iot-demo summary').click()
        page.get_by_role('button', name='Bật demo nhanh', exact=True).click()
        wait_for(lambda s: s['demo'], 'browser demo toggle')
        page.get_by_role('button', name='23:00', exact=True).click()
        wait_for(lambda s: s['clock'] == 'night' and s['mode'] == 'SLEEP', 'browser night clock')
        expect(page.locator('.iot-clock-state strong')).to_have_text('23:00 · Ban đêm (demo)')
        expect(modes.locator('button.selected strong')).to_have_text('Giờ ngủ')
        page.get_by_role('button', name='Tắt demo nhanh', exact=True).click()
        page.get_by_role('button', name='Giờ thật', exact=True).click()
        wait_for(lambda s: not s['demo'] and s['clock'] == 'real', 'restore normal settings')
        check('Dashboard mode, demo timer and clock controls reach the live controller')

        page.locator('.iot-demo summary').click()
        page.get_by_role('button', name='Bắt đầu trải nghiệm', exact=True).click()
        wait_for(lambda s: s['environment']['active'] and s['light'] == 'ON' and s['ac'] == 'ON', 'start experience and receive device acknowledgements')
        expect(page.locator('.iot-room-scene')).to_have_class('iot-room-scene light-on ac-on')
        check('One start button runs the automatic room and updates its illustration from device feedback')
        page.get_by_role('button', name='Tôi ra khỏi phòng', exact=True).click()
        wait_for(lambda s: s['motion'] == 0 and s['light'] == 'OFF', 'leave room and switch off the light')
        expect(light.get_by_role('button', name='Bật đèn phòng', exact=True)).to_be_enabled()
        wait_for(lambda s: s['ac'] == 'OFF', 'AC turns off after demo absence grace period', 22)
        check('Automatic mode still switches both devices off in an empty room')
        modes.get_by_role('button', name='Tự điều khiển', exact=False).click()
        wait_for(lambda s: s['mode']=='MANUAL', 'explicit manual selection')
        page.wait_for_timeout(16000)
        expect(modes.locator('button.selected strong')).to_have_text('Tự điều khiển')
        light.get_by_role('button', name='Bật đèn phòng', exact=True).click()
        wait_for(lambda s: s['light']=='ON' and s['motion']==0 and s['mode']=='MANUAL', 'browser light ON before arriving home')
        expect(page.locator('.iot-manual-hint')).to_contain_text('kể cả khi phòng vắng')
        page.screenshot(path=str(data_dir / 'dashboard-manual-away-desktop.png'), full_page=True)
        check('Manual selection stays selected beyond 15 seconds and permits light ON while away')
        modes.get_by_role('button', name='Tự động', exact=False).click()
        wait_for(lambda s: s['mode']=='AUTO' and s['light']=='OFF', 'resume AUTO while away')
        page.get_by_role('button', name='Tôi ở trong phòng', exact=True).click()
        wait_for(lambda s: s['motion'] == 1 and s['light'] == 'ON', 'return to room')

        page.screenshot(path=str(data_dir / 'dashboard-test-desktop.png'), full_page=True)
        page.set_viewport_size({'width': 390, 'height': 844})
        page.screenshot(path=str(data_dir / 'dashboard-test-mobile.png'), full_page=True)
        assert not page.evaluate('document.documentElement.scrollWidth > innerWidth'), 'Mobile horizontal overflow'
        page.get_by_role('button', name='Tắt đèn phòng', exact=True).click()
        wait_for(lambda s: s['mode'] == 'MANUAL' and s['light'] == 'OFF', 'mobile manual light command')
        page.get_by_role('button', name='Để nhà tự chăm ngay', exact=False).click()
        wait_for(lambda s: s['mode'] == 'AUTO' and s['light'] == 'ON', 'mobile resume automation')
        page.get_by_role('button', name='Dừng trải nghiệm', exact=True).click()
        wait_for(lambda s: not s['environment']['active'] and not s['environment']['requested'], 'stop experience and restore manual sensors')
        for width in [320, 768]:
            page.set_viewport_size({'width': width, 'height': 900})
            page.locator('.iot-demo summary').click()
            assert not page.evaluate('document.documentElement.scrollWidth > innerWidth'), f'Overflow at {width}px'
            page.locator('.iot-demo summary').click()
        check('Mobile device controls, return to automatic mode and stop experience all work')

        device_connection(False)
        wait_for(lambda s: s['status'] == 'offline', 'device disconnected')
        expect(page.get_by_role('button', name='Bắt đầu trải nghiệm', exact=True)).to_be_disabled()
        expect(page.get_by_role('button', name='Bật đèn phòng', exact=True)).to_be_disabled()
        expect(page.get_by_role('heading', name='Kết nối căn phòng để bắt đầu', exact=True)).to_be_visible()
        page.get_by_role('button', name='Xem cách kết nối', exact=False).click()
        expect(page.locator('.iot-help')).to_have_attribute('open', '')
        page.screenshot(path=str(data_dir / 'dashboard-test-offline.png'), full_page=True)
        check('Offline first use explains how to connect and opens its setup guide')
        device_connection(True)
        wait_for(lambda s: s['status'] == 'online', 'device reconnected')

        # The protected config endpoint supplies this run's isolated MQTT prefix.
        control('environment', True)
        wait_for(lambda s: s['environment']['active'], 'prepare isolated empty room for voice page')
        control('occupancy', 0)
        wait_for(lambda s: s['motion']==0 and s['light']=='OFF', 'empty room for voice controls')
        page.goto(url + '/voice/voice.html', wait_until='networkidle')
        page.get_by_role('heading', name='Nói một câu, nhà làm ngay.').wait_for()
        assert page.evaluate('BASE')==state()['baseTopic'], 'Voice must use isolated MQTT prefix'
        expect(page.locator('#roomPill')).to_have_text('Phòng đã kết nối', timeout=20000)
        page.get_by_role('button', name='Bật đèn', exact=True).click()
        wait_for(lambda s: s['mode']=='MANUAL' and s['light']=='ON' and s['motion']==0, 'voice page sends light ON while away')
        page.locator('.voice-settings').first.locator('summary').click()
        expect(page.locator('#manualRemaining')).to_contain_text('cả khi phòng vắng')
        check('Voice page sends manual light ON in an empty room using the isolated controller')
        page.get_by_role('button', name='Giảm nhiệt độ máy lạnh', exact=True).click()
        wait_for(lambda s: s['mode']=='MANUAL' and s['acTarget']==24, 'voice temperature button reaches controller')
        expect(page.locator('#targetTemperature')).to_have_text('24°C')
        control('autoTemperature',27)
        page.get_by_role('button', name='Tự động', exact=True).click()
        wait_for(lambda s: s['mode']=='AUTO' and s['acTarget']==27, 'voice switches to stored automatic target')
        expect(page.locator('#targetTemperature')).to_have_text('27°C')
        control('manualTemperature',25)
        control('autoTemperature',25)
        check('Voice page temperature controls and mode changes share the dashboard preferences')
        assert page.get_by_role('link', name='Về căn phòng', exact=False).get_attribute('href') == '/dashboard/room'
        page.set_viewport_size({'width': 390, 'height': 844})
        page.screenshot(path=str(data_dir / 'voice-test-mobile.png'), full_page=True)
        assert not page.evaluate('document.documentElement.scrollWidth > innerWidth'), 'Voice page mobile overflow'
        control('environment', False)
        wait_for(lambda s: not s['environment']['active'], 'stop isolated room after voice checks')

        page.goto(url + '/dashboard/room', wait_until='networkidle')
        environment_delivery(False)
        control('environment', True)
        wait_for(lambda s: bool(s['environment']['error']), 'missing environment acknowledgement reaches recoverable error', 40)
        expect(page.get_by_role('heading', name='Phòng chưa nhận được yêu cầu', exact=True)).to_be_visible()
        expect(page.get_by_role('button', name='Dừng trải nghiệm', exact=True)).to_be_enabled()
        expect(page.get_by_role('button', name='Tôi ra khỏi phòng', exact=True)).to_be_disabled()
        page.screenshot(path=str(data_dir / 'dashboard-recovery-waiting.png'), full_page=True)
        environment_delivery(True)
        wait_for(lambda s: s['environment']['active'] and not s['environment']['error'], 'automatic recovery without pressing retry', 25)
        check('A missing model ACK shows truthful pending UI and automatically recovers when delivery resumes')
        control('environment', False)
        wait_for(lambda s: not s['environment']['active'], 'stop recovered experience')
        environment_delivery(False)
        control('environment', True)
        wait_for(lambda s: s['environment']['phase']=='starting', 'pending start before cancellation')
        page.get_by_role('button', name='Dừng trải nghiệm', exact=True).click()
        wait_for(lambda s: not s['environment']['requested'] and not s['environment']['error'], 'cancel start while waiting for model ACK')
        environment_delivery(True)
        check('Stop remains usable while the simulator has not acknowledged the start')
        assert not errors, errors
        check('Desktop and mobile dashboard render without script errors or horizontal overflow')
        page.get_by_role('button',name='Đăng xuất',exact=True).click()
        page.wait_for_url('**/login')
        page.goto(url+'/dashboard/room')
        expect(page.get_by_role('button',name='Vào căn phòng',exact=True)).to_be_visible()
        check('Browser logout closes access to the dashboard')
        browser.close()
